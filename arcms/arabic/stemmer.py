"""مجذّع عربي خفيف مبني على خوارزمية Light10 (Larkey وآخرون) مع تعديلات صحفية.

المجذّع الخفيف لا يستخرج الجذر الثلاثي (فذلك يخلط «كاتب» بـ«مكتبة»)،
بل ينزع السوابق واللواحق الشائعة فقط: «بالاعتقال» و«الاعتقالات»
و«واعتقال» تصير كلها «اعتقال». يعمل على نص مُطبَّع مسبقاً (انظر normalize).
"""

from __future__ import annotations

# أدوات التعريف مرتبة من الأطول إلى الأقصر حتى لا تُنزع «ال» قبل «بال».
_ARTICLES = ("وبال", "وكال", "وفال", "وال", "بال", "كال", "فال", "لل", "ال")

# اللواحق بعد التطبيع (ة→ه، ى→ي) وبترتيب Light10 من اليمين إلى اليسار.
_SUFFIXES = ("ها", "ان", "ات", "ون", "ين", "يه", "ه", "ي")

# حروف الجر المتصلة التي قد تسبق اسماً غير معرَّف: «بغزة»، «لفلسطين».
# لا ندرج الفاء لأن أسماء كثيرة تبدأ بها أصلاً (فلسطين، فرنسا).
_CLITICS = ("ب", "ل", "ك")


def light_stem(word: str) -> str:
    """ينزع السوابق واللواحق وفق Light10. المدخل كلمة مُطبَّعة."""
    if not word or not word[0].isalpha() or not ("ء" <= word[0] <= "ي"):
        return word
    w = word
    # 1) واو العطف إذا بقي بعدها 3 أحرف فأكثر.
    if w.startswith("و") and len(w) - 1 >= 3:
        w = w[1:]
    # 2) أداة التعريف (مع حروف الجر الملتصقة بها) إذا بقي حرفان فأكثر.
    for art in _ARTICLES:
        if w.startswith(art) and len(w) - len(art) >= 2:
            w = w[len(art):]
            break
    # 3) اللواحق: مرور واحد على القائمة بالترتيب.
    for suf in _SUFFIXES:
        if w.endswith(suf) and len(w) - len(suf) >= 2:
            w = w[: -len(suf)]
    return w


def clitic_variant(word: str) -> str | None:
    """صورة الكلمة بعد نزع حرف جر/عطف متصل بغير المعرَّف («بغزه» → «غزه»).

    هذه الصورة تُفهرس مفتاحاً إضافياً فقط ولا تحل محل الكلمة، لأن النزع
    قد يكون خاطئاً في كلمات أصل حرفها الأول باء أو لام (بيروت، لندن).
    """
    rest = None
    if len(word) >= 5 and word[0] == "و" and word[1] in _CLITICS:
        rest = word[2:]  # عطف ثم جر: «وبغزة»
    elif len(word) >= 4 and word[0] in _CLITICS:
        rest = word[1:]
    if rest and not rest.startswith("ال"):
        return rest
    return None
