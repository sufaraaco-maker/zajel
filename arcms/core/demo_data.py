def silent_mp3(seconds: int = 20, tagged: bool = True) -> bytes:
    """ملف MP3 صامت صالح (إطارات MPEG-1 Layer III فارغة)، بوسوم ID3 مزيفة لتجربة نزعها."""
    frame = b"\xff\xfb\x90\x64" + bytes(413)  # 128kbps، 44.1kHz: 417 بايت للإطار
    body = frame * int(seconds * 44100 / 1152)
    if not tagged:
        return body
    payload = b"TPE1" + (13).to_bytes(4, "big") + b"\x00\x00" + b"\x00Reporter Name"[:13]
    header = b"ID3\x03\x00\x00" + bytes([0, 0, 0, len(payload)])
    return header + payload + body + b"TAG" + bytes(125)
